def build_lexicon():
    """建立正/負面詞集合 (已去重), 回傳 (pos_set, neg_set)。"""
    pos, neg = set(), set()
    for fn, s in (("ntusd_positive_utf8.txt", pos), ("ntusd_negative_utf8.txt", neg)):
        path = os.path.join(config.LEXICON_DIR, fn)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                for line in f:
                    w = line.strip()
                    if w:
                        s.add(w)
    pos.update(FIN_POSITIVE)
    neg.update(FIN_NEGATIVE)
    # 處理歧義詞: 同時出現於正/負面者視為中性, 從兩邊移除 (避免重複計數)
    ambig = pos & neg
    pos -= ambig
    neg -= ambig
    # 過濾: 僅保留長度 >=2 且不含空白/標點的字詞 (單字過於歧義, 造成大量誤判)
    def _clean(s):
        return {w for w in s if len(w.strip()) >= 2 and not any(ch.isspace() for ch in w)}
    pos = _clean(pos)
    neg = _clean(neg)
    return pos, neg


def build_weighted_lexicon():
    """建立加權詞典 (金融領域詞權重較高), 回傳 (pos_w, neg_w) dict。"""
    pos, neg = build_lexicon()
    fin_pos = {w for w in FIN_POSITIVE if len(w) >= 2}
    fin_neg = {w for w in FIN_NEGATIVE if len(w) >= 2}
    pos_w = {w: (2.0 if w in fin_pos else 1.0) for w in pos}
    neg_w = {w: (2.0 if w in fin_neg else 1.0) for w in neg}
    return pos_w, neg_w


